// Competition: u-suzy-one-line-one-laugh-roast-your-fridge-f1063521
// A single line that roasts the fridge — one line, one laugh.

// The line. One sentence, no setup, no punchline in a second sentence.
export const line =
  "My fridge hums like a jet engine all night, yet the only thing it has ever frozen is my hope of finding anything edible in there.";

export default line;

// Why the hum: every fridge has that one sound. It is not a gentle purr,
// it is a low, constant drone that follows you from the kitchen to the
// bedroom at 2 a.m. The joke starts there, with a noise everyone knows
// by heart, and then turns it into a jet engine — loud, proud, and
// completely useless at its actual job.

// Why the freezer: the roast only lands if the machine fails at the one
// thing it exists for. A fridge that cannot keep food edible is not an
// appliance, it is a loud cupboard with a light inside. So the line does
// not complain about the noise alone — it points out that all that noise
// produces nothing. The freezer works overtime and still delivers
// disappointment, which is the most honest review a fridge can get.

// The details behind the line: the yogurt that expired last month and
// nobody will throw away, the light that flickers instead of turning on,
// the ice tray that has been empty since summer. The line keeps only the
// two sharpest images — the jet-engine hum and the frozen hope — because
// a one-line roast has no room for a tour of the whole kitchen. Every
// word earns its place, and the ones that did not make the cut live here.

// Delivery: read it flat, let the contrast do the work. The first half
// sounds like a compliment — a machine powerful enough to fly — and the
// second half takes it all back. No shouting, no extra adjectives. The
// line is 129 characters long, well under the limit, and it stays one
// sentence so a judge reading it head-to-head gets the whole joke in a
// single breath.
